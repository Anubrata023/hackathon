function changeLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('suvidha_lang', lang);
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    const selects = document.querySelectorAll('select[onchange="changeLanguage(this.value)"]');
    selects.forEach(select => {
        if (select.value !== lang) select.value = lang;
    });
}

window.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('suvidha_lang') || 'en';
    // Small timeout to allow other DOM pieces to load before translating
    setTimeout(() => changeLanguage(savedLang), 50);
});